#!/usr/bin/env python3
"""Derive compact reviewable evidence; retain unabridged raw files in cache."""
from html.parser import HTMLParser
from pathlib import Path
import argparse,hashlib,json
parser=argparse.ArgumentParser();parser.add_argument('--cache',default=str(Path(__file__).resolve().parents[4]/'.cache/host-adapter-study/hosts'));args=parser.parse_args()
p=Path(__file__).resolve().parent;cache=Path(args.cache).resolve()
class P(HTMLParser):
 def __init__(self):super().__init__();self.skip=0;self.parts=[]
 def handle_starttag(self,t,a):
  if t in ['script','style','svg']:self.skip+=1
  if t in ['p','li','h1','h2','h3','h4','tr','br','pre']:self.parts.append('\n')
 def handle_endtag(self,t):
  if t in ['script','style','svg']:self.skip=max(0,self.skip-1)
 def handle_data(self,d):
  if not self.skip:self.parts.append(d)
manifest=json.loads((p/'fetch-manifest.json').read_text());parts=['# Primary-source excerpts','', 'Generated by summarize.py. L<n> are normalized-text/source line numbers; the body SHA256 in fetch-manifest.json authenticates original bytes. HTML normalization is lossy and is not a new independent source.','']
keys=['.agents/','.claude/','.github/','.cursor/','.gemini/','.opencode/','.codex/','~/.','AGENTS.md','GEMINI.md','SKILL.md','import','precedence','on-demand','automatically','hooks.json','plugin.json','source folder','config_folder','read_file','readFile','to_string','DEFAULT_SKILL','findImports','project_root','DirectorySymlinkPolicy','skills/','supports']
for row in manifest:
 if row.get('http',{}).get('http_code')!=200:continue
 f=Path(row['body_cache']);t=f.read_text(errors='replace')
 if '<html' in t.lower():q=P();q.feed(t);t=''.join(q.parts)
 (f.parent/(f.stem+'.txt')).write_text(t);lines=t.splitlines();seen=set();matches=[]
 for i,s in enumerate(lines):
  if any(k.lower() in s.lower() for k in keys) and s not in seen:
   seen.add(s);matches.append((i+1,s))
 parts+=['## '+row['id'],'',row['url'],'','sha256: `'+row['sha256']+'`; fetched: '+row['fetched_at_utc'],'']
 # Avoid nav menus; source files remain complete in cache.
 for n,s in matches[:45]:parts.append(f'L{n}: '+s[:1400].rstrip())
 parts.append('')
(p/'source-excerpts.md').write_text('\n'.join(parts)+'\n')
# Full CLI raw output is local cache, not the concise committed summary.
f=p/'probe-results.json'
if not f.exists():f=cache/'probe-results.full.json'
if f.exists():
 raw=f.read_bytes();(cache/'probe-results.full.json').write_bytes(raw);j=json.loads(raw);rows=[]
 for x in j['results']:
  stdout=x.pop('stdout','');stderr=x.pop('stderr','');tree=x.pop('home_tree',[]);x.update(stdout_sha256=hashlib.sha256(stdout.encode()).hexdigest(),stderr_sha256=hashlib.sha256(stderr.encode()).hexdigest(),stdout_excerpt=stdout[:250] if '--version' in x.get('argv',[]) else stdout[:1100],stderr_excerpt=stderr[:700],home_tree_count=len(tree),home_tree_sha256=hashlib.sha256(json.dumps(tree,sort_keys=True).encode()).hexdigest());rows.append(x)
 j.update(full_raw_cache=str(cache/'probe-results.full.json'),full_raw_sha256=hashlib.sha256(raw).hexdigest(),results=rows);(p/'probe-summary.json').write_text(json.dumps(j,ensure_ascii=False,indent=2)+'\n')
# The discovery RPC includes bundled skills; summarize only our fixtures.
f=p/'discovery-results.json'
if not f.exists():f=cache/'discovery-results.full.json'
if f.exists():
 raw=f.read_bytes();(cache/'discovery-results.full.json').write_bytes(raw);j=json.loads(raw)
 for x in j['results']:
  for msg in x.pop('received',[]):
   if msg.get('id')==2:
    x['rpc_error']=msg.get('error');x['discovered']=[{k:s.get(k) for k in ['name','path','scope','enabled']} for d in msg.get('result',{}).get('data',[]) for s in d.get('skills',[]) if s['name'].startswith(('project-','global-'))]
 j.update(full_raw_cache=str(cache/'discovery-results.full.json'),full_raw_sha256=hashlib.sha256(raw).hexdigest());(p/'discovery-summary.json').write_text(json.dumps(j,ensure_ascii=False,indent=2)+'\n')
# A compact URL/date/hash catalog for review.
rows=['# Snapshot catalog','','All fetched 2026-11-10 UTC; exact timestamps, argv, HTTP result, failures and full hashes are in fetch-manifest.json. Bodies/headers remain in the ignored cache. Fixed source commits appear in sources.json.','','| ID | Status | SHA256 | URL |','|---|---|---|---|']
for x in manifest:rows.append('| '+x['id']+' | '+str(x.get('http',{}).get('http_code'))+'/'+str(x['exit_code'])+' | `'+x.get('sha256','—')+'` | '+x['url']+' |')
(p/'snapshot-catalog.md').write_text('\n'.join(rows)+'\n')
